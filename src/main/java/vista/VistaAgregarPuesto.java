	private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnEditarActionPerformed
		int fliaSelected = jTable1.getSelectedRow();
		if (fliaSelected != -1) {
			String idPuesto = (String) jTable1.getValueAt(fliaSelected, 0);
			int confirmacion = JOptionPane.showConfirmDialog(null,
					"¿Estás seguro que deseas editar al cliente con ID " + idPuesto + "?", "Confirmar editar",
					JOptionPane.YES_NO_OPTION);
			if (confirmacion == JOptionPane.YES_OPTION) {
				VistaEditarPuesto vep = new VistaEditarPuesto(idPuesto,token);
				vep.setVisible(true);
				this.dispose();

			} else {
				JOptionPane.showMessageDialog(null, "No se edito el puesto");
			}
			return;
		}
		JOptionPane.showMessageDialog(null, "Se edito  correctamente"); // TODO add your handling code here:
	}// GEN-LAST:event_btnEditarActionPerformed

	private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) throws Exception {// GEN-FIRST:event_btnEliminarActionPerformed
		int filaSeleccionada = jTable1.getSelectedRow();

        if (filaSeleccionada != -1) {
            String idVideojuego = (String) jTable1.getValueAt(filaSeleccionada, 0);
            int confirmacion = JOptionPane.showConfirmDialog(null, "¿Estás seguro que deseas eliminar al puesto con ID " + idVideojuego + "?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
            if (confirmacion == JOptionPane.YES_OPTION) {
                this.puesto.eliminarPuesto(idVideojuego,token);
                // Mostrar mensaje de éxito
                JOptionPane.showMessageDialog(null, "Puesto eliminado exitosamente");
                // Recargar la tabla

                llenarTabla();
            }
        } else {
            // Mostrar mensaje si no hay fila seleccionada
            JOptionPane.showMessageDialog(null, "Se debe seleccionar un pueste de la tabla para poderlo eliminar");
        }// TODO add your handling code here:
	}// GEN-LAST:event_btnEliminarActionPerformed

	private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) throws Exception {// GEN-FIRST:event_btnBuscarActionPerformed
		
			if (!(txtId.getText().isEmpty())) {
				String id = txtId.getText();
				Puesto puestoBuscado = PuestoApiClient.buscarPuestoPorId(id,token);
				if (puestoBuscado != null) {
					JOptionPane.showMessageDialog(null, "El puesto fue encontrado");

					Puesto puesto = PuestoApiClient.buscarPuestoPorId(id,token);
					if (puesto != null) {
						DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
						modelo.setRowCount(0);
						Object[] row = new Object[5];
						row[0] = puesto.getId();
						row[1] = puesto.getNumeroDePuesto();
						row[2] = puesto.getConsola().getConsola();
						row[3] = puesto.getCantidadDeSillas();
						row[4] = puesto.getCanditadDeControles();

						modelo.addRow(row);

					} else {
						JOptionPane.showMessageDialog(null, "El puesto no fue encontrado");
					}
				} else {
					JOptionPane.showMessageDialog(null, "Por favor ingrese un id o un numero de puesto");
				}
			}
		} // TODO add your handling code here:
	// GEN-LAST:event_btnBuscarActionPerformed

