    private void llenarDatos(String id){
		try {
			VideoJuego videojuego = videojuegoClient.buscarVideojuegoPorId(id);
			txtNombre.setText(videojuego.getNombre());
			txtDescripcion.setText(videojuego.getDescripcion());
			txtClasificacion.setText(videojuego.getPublico());
			txtTipo.setText(videojuego.getTipo());
			jComboBox1.setSelectedItem(String.valueOf(videojuego.getFechaDePubliacion().getYear()));
			jComboBox2.setSelectedItem(String.valueOf(videojuego.getFechaDePubliacion().getMonthValue()));
			jComboBox3.setSelectedItem(String.valueOf(videojuego.getFechaDePubliacion().getDayOfMonth()));
		} catch (Exception e) {
			JOptionPane.showMessageDialog(this, "Error al cargar los datos del videojuego", "Error", JOptionPane.ERROR_MESSAGE);
		}
	}
