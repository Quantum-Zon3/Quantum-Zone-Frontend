    private void btnAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAñadirActionPerformed
        try {
            String descripcion = txtDescripcion.getText();
            String nombre = txtNombre.getText();
            String clasificacion = txtClasificacion.getText();
            int Año = Integer.parseInt((String) jComboBox1.getSelectedItem());
            int Mes = jComboBox2.getSelectedIndex()+1;
            int Dia = Integer.parseInt((String) jComboBox3.getSelectedItem());
            String tipo = txtTipo.getText();
            LocalDate fechaPublicacion = LocalDate.of(Año, Mes, Dia);
            if (txtDescripcion.equals(null) || txtNombre.equals(null) || txtClasificacion.equals(null) || txtTipo.equals(null) || jComboBox1.getSelectedIndex() == 0 || jComboBox2.getSelectedIndex() == 0 || jComboBox3.getSelectedIndex() == 0) {
                JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            VideoJuego videojuego = new VideoJuego(nombre,fechaPublicacion, descripcion,clasificacion,tipo );
            videojuegoClient.actualizarVideojuego(this.idVideojuego, videojuego);
            JOptionPane.showMessageDialog(this, "Videojuego editado correctamente");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese valores válidos en los campos", "Entrada inválida", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al editar el videojuego", "Error", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }
